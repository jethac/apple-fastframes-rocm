#!/usr/bin/env python3
"""Generate a naive single-tile BF16 GEMM for XDNA2 (AIE2P) in Loom IR.

C[M,N] (f32) = A[M,K] (bf16) @ B[K,N] (bf16)

Operands are pre-packed on the host into 8-wide panels so each k-step's
8-element column of A / row of B is contiguous:
  Ap[M/8][K][8]  (Ap[i][k][r] = A[8i+r, k])
  Bp[N/8][K][8]  (Bp[j][k][c] = B[k, 8j+c])
Each 8x8 output tile accumulates K bf16 outer products with vector.mma
(lowered to AIE2P mma.bf16bf16.m8n8k1, f32 accumulator), loading KC k-steps
of each panel per global vector load.

The kernel.def uses one workgroup (one AIE core). Optionally TM/TN
workgroups (grid) partition the output tiles: --grid GX.

Usage: python gemm_gen.py M K N out.loom [--kc 32] [--grid G] [--npy dir]
"""
import argparse

ap = argparse.ArgumentParser()
ap.add_argument("M", type=int); ap.add_argument("K", type=int); ap.add_argument("N", type=int)
ap.add_argument("out")
ap.add_argument("--kc", type=int, default=32, help="k-steps per global load")
ap.add_argument("--grid", type=int, default=1, help="workgroups (x)")
ap.add_argument("--npy", default=None, help="dir holding ap.npy/bp.npy; adds check.case")
a = ap.parse_args()
M, K, N, KC, G = a.M, a.K, a.N, a.kc, a.grid
assert M % 8 == 0 and N % 8 == 0 and K % KC == 0
TM, TN = M // 8, N // 8
TILES = TM * TN
assert TILES % G == 0
PER = TILES // G
CH = KC * 8  # bf16 elements per chunk

slices = []
for s in range(KC):
    slices.append(f"""
        %a{s} = vector.slice %achunk[{8*s}] : vector<{CH}xbf16> -> vector<8xbf16>
        %b{s} = vector.slice %bchunk[{8*s}] : vector<{CH}xbf16> -> vector<8xbf16>
        %fa{s} = vector.fragment<lhs> %a{s} shape [%c8, %c1] : vector<8xbf16>
        %fb{s} = vector.fragment<rhs> %b{s} shape [%c1, %c8] : vector<8xbf16>
        %acc{s+1} = vector.mma %fa{s}, %fb{s}, %acc{s} : vector<8xbf16>, vector<8xbf16>, vector<64xf32>""")
body = "".join(slices)
store = "".join(f"""
    %row{r} = index.add %r0, %c{r}r : index
    %rowv{r} = vector.slice %res[{8*r}] : vector<64xf32> -> vector<8xf32>
    vector.store %rowv{r}, %C[%row{r}, %cc0] : vector<8xf32>, view<{M}x{N}xf32>""" for r in range(8))
consts = "".join(f"""
  %c{r}r = index.constant {r} : index""" for r in range(8))

wg = ""
if G > 1:
    wg_id = "%wid = kernel.workgroup.id<x> : index"
else:
    wg_id = "%wid = index.constant 0 : index"

src = f"""// Generated by gemm_gen.py: M={M} K={K} N={N} KC={KC} grid={G}
kernel.def @gemm_bf16() {{
  %g = index.constant {G} : index
  %c1k = index.constant 1 : index
  kernel.launch.config workgroups(%g, %c1k, %c1k) workgroup_size(%c1k, %c1k, %c1k) : index
}} launch(%ap_arg: buffer, %bp_arg: buffer, %c_arg: buffer) {{
  %ap, %bp, %cbuf = buffer.assume.alignment %ap_arg, %bp_arg, %c_arg {{minimum_alignment = 64}} : buffer, buffer, buffer
  %origin = index.constant 0 : offset
  %A = buffer.view %ap[%origin] : buffer -> view<{TM*K*8}xbf16>
  %B = buffer.view %bp[%origin] : buffer -> view<{TN*K*8}xbf16>
  %C = buffer.view %cbuf[%origin] : buffer -> view<{M}x{N}xf32>
  %c0 = index.constant 0 : index
  %c1 = index.constant 1 : index
  %c8 = index.constant 8 : index
  %cK = index.constant {K} : index
  %cKC = index.constant {KC} : index
  %cTN = index.constant {TN} : index
  %cPER = index.constant {PER} : index
  %panel = index.constant {K*8} : index{consts}
  {wg_id}
  %t0 = index.mul %wid, %cPER : index
  %t1 = index.add %t0, %cPER : index
  scf.for %t = [%t0 to %t1 step %c1] {{
    %ti = index.div %t, %cTN : index
    %tj = index.rem %t, %cTN : index
    %abase = index.mul %ti, %panel : index
    %bbase = index.mul %tj, %panel : index
    %zero = vector.splatf 0.0 : vector<64xf32>
    %init = vector.fragment<init> %zero shape [%c8, %c8] : vector<64xf32>
    %res = scf.for %k0 = [%c0 to %cK step %cKC](%acc0 = %init : vector<64xf32>) -> (vector<64xf32>) {{
      %koff = index.mul %k0, %c8 : index
      %aoff = index.add %abase, %koff : index
      %boff = index.add %bbase, %koff : index
      %achunk = vector.load %A[%aoff] : view<{TM*K*8}xbf16> -> vector<{CH}xbf16>
      %bchunk = vector.load %B[%boff] : view<{TN*K*8}xbf16> -> vector<{CH}xbf16>{body}
      scf.yield %acc{KC} : vector<64xf32>
    }}
    %r0 = index.mul %ti, %c8 : index
    %cc0 = index.mul %tj, %c8 : index
{store}
  }}
  kernel.return
}}
"""
if a.npy:
    src += f"""
check.case public @gemm_npy {{
  %ap = check.file.read.npy path("{a.npy}/ap.npy") : tensor<{TM*K*8}xi16>
  %bp = check.file.read.npy path("{a.npy}/bp.npy") : tensor<{TN*K*8}xi16>
  %c = check.generate.fill value(-777.0) : tensor<{M*N}xf32>
  kernel.launch @gemm_bf16(%ap, %bp, %c) : (tensor<{TM*K*8}xi16>, tensor<{TN*K*8}xi16>, tensor<{M*N}xf32>)
  check.file.write.npy value(%c) path("c.npy") mode(always) : tensor<{M*N}xf32>
  check.return
}}

check.benchmark<@gemm_npy> @gemm_bench
"""
open(a.out, "w").write(src)
